export const APPLICATION_STATUS = Object.freeze({
  DRAFT: 'DRAFT',
  SUBMITTED: 'SUBMITTED',
  UNDER_REVIEW: 'UNDER_REVIEW',
  FLAGGED: 'FLAGGED',
  ACCEPTED: 'ACCEPTED',
  REJECTED: 'REJECTED',
});

export const STATUS_LIST = Object.values(APPLICATION_STATUS);

export const VALID_TRANSITIONS = Object.freeze({
  [APPLICATION_STATUS.DRAFT]: [APPLICATION_STATUS.SUBMITTED],
  [APPLICATION_STATUS.SUBMITTED]: [APPLICATION_STATUS.UNDER_REVIEW, APPLICATION_STATUS.FLAGGED, APPLICATION_STATUS.ACCEPTED, APPLICATION_STATUS.REJECTED],
  [APPLICATION_STATUS.UNDER_REVIEW]: [APPLICATION_STATUS.ACCEPTED, APPLICATION_STATUS.REJECTED, APPLICATION_STATUS.FLAGGED],
  [APPLICATION_STATUS.FLAGGED]: [APPLICATION_STATUS.SUBMITTED],
  [APPLICATION_STATUS.ACCEPTED]: [],
  [APPLICATION_STATUS.REJECTED]: [],
});

export const isValidTransition = (currentStatus, targetStatus) => {
  const allowed = VALID_TRANSITIONS[currentStatus] || [];
  return allowed.includes(targetStatus);
};
